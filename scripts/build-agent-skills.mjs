import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const agentSkillNames = ['analyzer', 'translator', 'integration', 'verifier'];

// Compile Markdown at build time. Installed CJS bundles and source ESM execution
// share the same instructions without cwd-dependent file searches or fallbacks.
export async function buildAgentSkills({ check = false } = {}) {
  const skills = {}, versions = {};
  for (const name of agentSkillNames) {
    const directory = path.join(repositoryRoot, 'skills', name);
    const entry = (await readFile(path.join(directory, 'SKILL.md'), 'utf8')).replaceAll('\r\n', '\n');
    if (!entry.startsWith(`---\nname: recast-${name}\ndescription: `) || !entry.includes('\n---\n')) {
      throw new Error(`Invalid skill entry: ${name}/SKILL.md`);
    }
    const digest = createHash('sha256').update(entry);
    const sections = {};
    for (const file of (await readdir(path.join(directory, 'references'))).filter(file => file.endsWith('.md')).sort()) {
      const source = (await readFile(path.join(directory, 'references', file), 'utf8')).replaceAll('\r\n', '\n');
      digest.update(file).update('\0').update(source);
      const matches = [...source.matchAll(/^## ([a-z][a-z0-9-]*)\n\n```text\n([\s\S]*?)\n```(?=\n|$)/gm)];
      if (matches.length === 0 || matches.length !== (source.match(/^## /gm) ?? []).length) {
        throw new Error(`Invalid instruction sections: ${name}/references/${file}`);
      }
      for (const [, section, text] of matches) {
        const key = `${file.slice(0, -3)}/${section}`;
        if (!text.trim() || Object.hasOwn(sections, key)) throw new Error(`Empty or duplicate skill section: ${name}/${key}`);
        sections[key] = text;
      }
    }
    skills[name] = sections;
    versions[name] = digest.digest('hex');
  }
  const banner = '// Generated by scripts/build-agent-skills.mjs from skills/*; edit the Markdown sources.\n';
  const javascript = banner + `const skills = ${JSON.stringify(skills, null, 2)};\n\n` +
    `export const skillVersions = Object.freeze(${JSON.stringify(versions, null, 2)});\n\n` +
    `export function skillInstruction(skill, section) {\n` +
    `  if (!Object.hasOwn(skills, skill) || !Object.hasOwn(skills[skill], section)) {\n` +
    '    throw new Error(`Unknown RECAST skill section: ${skill}/${section}`);\n' +
    `  }\n  return skills[skill][section];\n}\n`;
  const types = banner + 'interface SkillSections {\n' + Object.entries(skills).map(([name, sections]) =>
    `  ${name}: ${Object.keys(sections).map(key => JSON.stringify(key)).join(' | ')};`).join('\n') + '\n}\n' +
    'export declare const skillVersions: Readonly<Record<keyof SkillSections, string>>;\n' +
    'export declare function skillInstruction<S extends keyof SkillSections>(skill: S, section: SkillSections[S]): string;\n';
  for (const [name, expected] of [['compiled.mjs', javascript], ['compiled.d.mts', types]]) {
    const file = path.join(repositoryRoot, 'skills', name);
    const actual = await readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
    if (actual.replaceAll('\r\n', '\n') === expected) continue;
    if (check) throw new Error(`Stale ${name}: run npm run skills:build`);
    await writeFile(file, expected, 'utf8');
  }
  return versions;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildAgentSkills({ check: process.argv.includes('--check') });
  console.log('RECAST agent skills ready (4 bundles).');
}
